// ── PRIMARY KEYS ARE GENERATED BY PRISMA, NOT BY POSTGRES ────────────────────────────────────────
// `id` is declared `@default(uuid())` or `@default(cuid())` in schema.prisma, and Prisma fills it in
// its own client layer — the COLUMN has no database default at all. Anything reaching these tables
// by raw SQL, as this loader does, must therefore supply the key itself or die on a NOT NULL
// violation. Which kind is per-model, so it is read out of schema.prisma rather than assumed: the
// tables in this workbook are not consistent with each other (shareholding_patterns is uuid, the
// financial tables are cuid), and writing the wrong shape would leave one table with two id formats.
/** table name -> "uuid" | "cuid", straight from the schema's own @default on the id field. */
function readIdKinds(): Map<string, "uuid" | "cuid"> {
  const out = new Map<string, "uuid" | "cuid">();
  const src = fs.readFileSync("prisma/schema.prisma", "utf8");
  for (const block of src.split(/\nmodel\s+/).slice(1)) {
    const map = /@@map\("([^"]+)"\)/.exec(block);
    const def = /\bid\s+String\s+@id\s+@default\((uuid|cuid)\(\)\)/.exec(block);
    if (map && def) out.set(map[1], def[1] as "uuid" | "cuid");
  }
  return out;
}
/** cuid v1: 'c' + time(base36) + counter + fingerprint + randomness = 25 chars, exactly the shape
 *  already in these tables. Reimplemented because Prisma does not export its generator. */
let cuidCount = Math.floor(Math.random() * 1679616);
const cuidFingerprint = (() => {
  const pid = process.pid.toString(36).padStart(2, "0").slice(-2);
  const host = os.hostname().split("").reduce((a, c) => a + c.charCodeAt(0), os.hostname().length + 36);
  return pid + host.toString(36).padStart(2, "0").slice(-2);
})();
const b36 = (n: number, w: number): string => Math.floor(n).toString(36).padStart(w, "0").slice(-w);
function cuid(): string {
  cuidCount = (cuidCount + 1) % 1679616;
  return `c${b36(Date.now(), 8)}${b36(cuidCount, 4)}${cuidFingerprint}${b36(Math.random() * 1679616, 4)}${b36(Math.random() * 1679616, 4)}`;
}

