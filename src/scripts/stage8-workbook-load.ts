// STAGE 8 — LOAD THE FILLED WORKBOOK BACK INTO THE DATABASE.
//
//   npx tsx src/scripts/stage8-workbook-load.ts                      # validate only — writes NOTHING
//   npx tsx src/scripts/stage8-workbook-load.ts --apply              # write
//   npx tsx src/scripts/stage8-workbook-load.ts --only quarterly_results
//   npx tsx src/scripts/stage8-workbook-load.ts --dir X --verbose
//
// ── THE GUARANTEES ───────────────────────────────────────────────────────────────────────────────
//  1. IT NEVER OVERWRITES. A row that exists is filled ONLY where it is NULL, via
//     `SET col = COALESCE(col, $v)`. Automated data always wins over a hand-typed value, because the
//     automated path has a source URL and a parser that refused what it could not read.
//  2. IT NEVER WRITES AN EMPTY ROW. A row with no values is skipped, not inserted. An empty row
//     reads as complete to every consumer while occupying a retention slot — worse than the gap.
//  3. IT VALIDATES BEFORE IT WRITES. Unknown symbol, unparseable number, a column the table does not
//     have, a NOT NULL column with nothing to put in it, a fiscal-year label that contradicts its own
//     report date, a figure two orders of magnitude away from that company's own history — each is
//     REPORTED BY NAME and skipped. The run does not stop, so one bad cell cannot cost a session.
//  4. IT IS RE-RUNNABLE. Load a half-finished workbook as often as you like; already-present values
//     are left alone and reported as `unchanged`.
//
// Column names never reach SQL unchecked — every one is validated against information_schema first.
//
// ── WHAT THE FIRST REAL WORKBOOK TAUGHT THIS SCRIPT ──────────────────────────────────────────────
// Written against the schema in the abstract, it had six defects that only a filled workbook exposes.
// Each is now handled here, and each is worth naming because the next importer will meet them again:
//
//  A. ⚠ FISCAL-YEAR LABEL WIDTH. The workbook says `FY2025`; every table in this database stores
//     `FY25`, and that label is PART OF THE UNIQUE KEY. Loading it verbatim would have matched no
//     existing row (so every fill became an insert), created a parallel 4-digit universe alongside
//     the real one, and — worse — `decrementFY` in fiscal.ts matches /^FY(\d{2})$/ and THROWS on
//     anything else, so the poison would surface later, in scoring, far from its cause. Normalised
//     here, and cross-checked against the row's own report date.
//  B. `symbol` EXISTS ON ONE TABLE ONLY (shareholding_patterns). The rest key on stock_id alone.
//  C. `source` LIKEWISE DOES NOT EXIST on shareholding_patterns, and `updated_at` does not either.
//  D. SHAREHOLDING'S NATURAL KEY IS (stock_id, as_on_date) — that is the unique index. Matching on
//     (fiscal_year, quarter) is not the same thing: intra-quarter filings put two rows in one
//     quarter, so that key can resolve to the WRONG row, and an insert can hit the index instead.
//  E. total_shares / promoter_shares / pledged_shares are int8. A JS number is not a BigInt.
//  F. A UTF-8 BOM on the first header cell turns `symbol` into an unmatchable name, and every row
//     then fails with "unknown symbol" — a whole file lost to an invisible character.
// ═══════════════════════════════════════════════════════════════════════════════════════════════════
